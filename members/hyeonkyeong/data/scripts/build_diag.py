FILES = {'a': ('1-7', range(1, 8)), 'b': ('8-13', range(8, 14)), 'c': ('14-20', range(14, 21))}


def load_master():
    m = {}
    for f in sorted(glob.glob(os.path.join(MASTER_DIR, 'H1-*indicator_master*.json'))):
        for r in json.load(open(f, encoding='utf-8')):
            m[r['id']] = r
    return m


M = load_master()
for key, (name, ids) in FILES.items():
    path = os.path.join(DATA, 'diag_%s.csv' % name)
    with open(path, 'w', encoding='utf-8-sig', newline='') as fp:
        w = csv.writer(fp)
        w.writerow(['문항ID', '지표번호', '지표명', '유형', '질문', '정답', '근거(마스터 definition)'])
        for i in ids:
            for n, (typ, q, a) in enumerate(Q[i], 1):
                w.writerow(['T-%s-%02d-%d' % (key, i, n), i, M[i]['name'], typ, q, a, M[i]['definition']])
    print(path, sum(len(Q[i]) for i in ids), '문항')
