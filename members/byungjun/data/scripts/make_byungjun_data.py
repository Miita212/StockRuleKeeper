def has_batchim(s):
    c = s[-1]
    if "가" <= c <= "힣":
        return (ord(c) - 0xAC00) % 28 != 0
    return c.upper() in "RLMN"  # PER, PBR 등 영문 약어는 '알' 받침으로 읽음


def eun(s):
    return s + ("은" if has_batchim(s) else "는")


def eul(s):
    return s + ("을" if has_batchim(s) else "를")


def euro(s):
    c = s[-1]
    batchim = "가" <= c <= "힣" and (ord(c) - 0xAC00) % 28 not in (0, 8)
    return s + ("으로" if batchim else "로")


def ie(s):
    return s + ("이에요" if has_batchim(s) else "예요")


def num(v):
    return f"{v:g}"


def vtxt(v, unit):
    if unit == "억원":
        if v >= 10000 and v % 10000 == 0:
            return f"{int(v // 10000)}조원"
        if v >= 1000 and v % 1000 == 0:
            return f"{int(v // 1000)}천억원"
        return f"{num(v)}억원"
    return f"{num(v)}{unit}"


def cond(i, v):
    if i["id"] in (16, 17):  # 화면 문구 '이내' (규칙 2)
        return f"{num(v)}% 이내"
    return f"{vtxt(v, i['unit'])} {OPWORD[i['op']]}"


